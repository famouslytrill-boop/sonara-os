#!/usr/bin/env node

// Generate docs/SONARA_RECOMMENDED_PRODUCT_CATALOG_2026.md from the catalog.
//
// The document this replaces was written by hand in July and never touched
// again. By August it listed thirty-four products under names the code had
// stopped using, opened with "SONARA Nexus Shared Operating Spine" -- a retired
// public name AGENTS.md forbids in launch docs -- and repeated the count 34 in
// five places, along with a 10/8/8/8 company breakdown that had been wrong
// since the first product was removed.
//
// Nothing referenced it, which is why none of that failed anything. That is the
// argument for generating it rather than correcting it: a hand-written list of
// what the catalog contains disagrees with the catalog the moment the catalog
// changes, and the only thing that noticed was a person reading it.
//
// The policy prose below is deliberately not derived. It states what the rules
// are, and rules are not a fact about the code -- but the numbers, names,
// lifecycle states and plan floors are, and those come from the module.

import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const root = process.cwd();
const OUTPUT = path.join(root, "docs", "SONARA_RECOMMENDED_PRODUCT_CATALOG_2026.md");
const checkOnly = process.argv.includes("--check");

const {
  CATALOG_VERSION,
  RECOMMENDED_PRODUCT_CATALOG,
  getRecommendedProductCatalogSummary
} = require(path.join(root, "lib", "sonara-recommended-product-catalog.cjs"));
const { hasEnforcedPaidAccess } = require(path.join(root, "lib", "sonara-paid-access.cjs"));

const COMPANIES = [
  ["sonara_industries", "SONARA Industries shared products"],
  ["business_builder", "Business Builder products"],
  ["creator_studio", "Creator Studio products"],
  ["growth_studio", "Growth Studio products"]
];

const PLAN_LABEL = { free: "Free", starter: "Starter", core: "Core", pro: "Pro" };

const problems = [];
const summary = getRecommendedProductCatalogSummary();

// A generated document that describes an empty catalog would still be
// internally consistent, and would still read as if everything were fine.
if (RECOMMENDED_PRODUCT_CATALOG.length < 20) {
  problems.push(`The catalog is down to ${RECOMMENDED_PRODUCT_CATALOG.length} products. Check that before publishing a document about it.`);
}
for (const [productKey] of COMPANIES) {
  if (!RECOMMENDED_PRODUCT_CATALOG.some((item) => item.productKey === productKey)) {
    problems.push(`No product belongs to ${productKey}, so its section would publish empty.`);
  }
}
// AGENTS.md forbids retired public names in launch docs, and this is one. The
// old version of this file opened with the worst offender.
for (const item of RECOMMENDED_PRODUCT_CATALOG) {
  if (/\bnexus\b/i.test(`${item.name} ${item.summary}`)) {
    problems.push(`${item.serviceKey} carries a retired public name.`);
  }
}

const cell = (value) => String(value ?? "").replace(/\|/g, "\\|").replace(/\s+/g, " ").trim();

const lines = [];
lines.push("# SONARA Recommended Product Catalog — 2026");
lines.push("");
lines.push("GENERATED by `scripts/generate-product-catalog-doc.mjs` from");
lines.push("`lib/catalog/*.cjs`. Edit the catalog, then regenerate — editing this file");
lines.push("by hand puts it back to disagreeing with the product it describes.");
lines.push("");
lines.push(`**Version:** ${CATALOG_VERSION}  `);
lines.push(`**Products:** ${summary.total}  `);
lines.push(`**Open to customers:** ${summary.executionEnabled}  `);
lines.push(`**Restricted:** ${summary.executionRestricted}`);
lines.push("");
lines.push("Each entry declares its plan floor, delivery state, route, and whether the");
lines.push("server will actually let a customer run it. A published entry is not");
lines.push("automatically an executable one.");
lines.push("");
lines.push("## Portfolio rules");
lines.push("");
lines.push("- Keep the connected path from business launch, to creator operations, to measurable growth.");
lines.push("- Prefer complete governed workflows over large collections of disconnected features.");
lines.push("- Preserve the Free, Starter, Core, and Pro plan families. This catalog does not create or change Stripe prices.");
lines.push("- A paid plan floor is only honest where the server enforces an entitlement for that product family. Where it does not, price the product free or map the entitlement — do not publish a plan that buys nothing.");
lines.push("- Keep provider-backed execution setup-gated and approval-gated.");
lines.push("- Do not present `validation_required`, `planned`, or `setup_required` products as complete.");
lines.push("- Preserve the done-for-you service catalog alongside the software product catalog.");
lines.push("");
lines.push("## Delivery states");
lines.push("");
lines.push("| Status | Meaning | Can execute |");
lines.push("|---|---|---|");
lines.push("| `active` | The workflow is available. | Yes |");
lines.push("| `beta` | A real workflow exists; coverage or integration depth is incomplete. | Yes |");
lines.push("| `validation_required` | Approved for testing; customer commitment is needed before full build. | No |");
lines.push("| `planned` | Approved directionally. Must not be sold as complete. | No |");
lines.push("| `setup_required` | Depends on customer, provider, or production configuration. | No |");
lines.push("");

for (const [productKey, heading] of COMPANIES) {
  const items = RECOMMENDED_PRODUCT_CATALOG.filter((item) => item.productKey === productKey);
  lines.push(`## ${heading}`);
  lines.push("");
  lines.push("| Product | Plan | State | Route | Open |");
  lines.push("|---|---|---|---|---|");
  for (const item of items) {
    lines.push(
      `| ${cell(item.name)} | ${PLAN_LABEL[item.planFloor] || cell(item.planFloor)} | \`${cell(item.lifecycleStatus)}\` | \`${cell(item.route)}\` | ${item.executionEnabled ? "Yes" : "No"} |`
    );
  }
  lines.push("");
}

lines.push("## Where this lives in the code");
lines.push("");
lines.push("- `lib/catalog/*.cjs` holds the definitions. `lib/sonara-recommended-product-catalog.cjs` assembles them and computes the execution boundary.");
lines.push("- `lib/sonara-paid-access.cjs` names the entitlement keys the server actually enforces. A paid product outside that map cannot open, by construction.");
lines.push("- `scripts/generate-catalog-sync-migration.cjs` writes the migration that publishes these rows to `service_catalog_items` and retires the ones the catalog has dropped.");
lines.push("- `scripts/verify-production-product-catalog.mjs` compares the live database against this catalog and gates the production deploy on it. Its expected counts are read from the catalog, not written down a second time.");
lines.push("- `/service-catalog` merges the database rows over these definitions, so the database wins on anything it holds.");
lines.push("");
lines.push("## Paid access");
lines.push("");
lines.push("The server reads active `billing_entitlements` first, then active or trialing");
lines.push("`billing_subscriptions`. Missing or unmapped billing state fails closed.");
lines.push("");
lines.push("This catalog once defined \"paid access is verified\" as `planFloor === \"free\"`,");
lines.push("which made every paid product permanently shut while reporting the state as");
lines.push("pending work. It is now the question the code can actually answer: whether");
lines.push("`lib/sonara-paid-access.cjs` maps an entitlement key for the product's family.");
lines.push("");
const enforced = COMPANIES.map(([productKey]) => `${productKey} ${hasEnforcedPaidAccess(productKey) ? "enforced" : "not enforced"}`).join(", ");
lines.push(`Current enforcement: ${enforced}.`);
lines.push("");
lines.push("A positive end-to-end test — a real production account on the intended plan");
lines.push("granted access, and a lower-plan account denied — has not been run. That is");
lines.push("recorded in `docs/SHIP_READINESS.md` as owner work, and it is separate from");
lines.push("whether the mapping exists.");
lines.push("");

const generated = lines.join("\n");

if (problems.length) {
  for (const problem of problems) console.error(`ERROR: ${problem}`);
  process.exit(1);
}

if (checkOnly) {
  const existing = fs.existsSync(OUTPUT) ? fs.readFileSync(OUTPUT, "utf8") : "";
  if (existing !== generated) {
    console.error(`ERROR: ${path.relative(root, OUTPUT)} is out of date. Run: node scripts/generate-product-catalog-doc.mjs`);
    process.exit(1);
  }
  console.log(`Product catalog document verified: ${summary.total} products, ${summary.executionEnabled} open, ${summary.executionRestricted} restricted.`);
} else {
  fs.writeFileSync(OUTPUT, generated);
  console.log(`Wrote ${path.relative(root, OUTPUT)}: ${summary.total} products.`);
}
