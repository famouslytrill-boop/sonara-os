import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import { markdownTableCell as cell } from "./markdown-table-cell.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(import.meta.url);
const from = (name) => require(path.join(root, name));
const files = (dir) => fs.readdirSync(path.join(root, dir)).sort();
// Stable code-point sort: localeCompare changes between Node/ICU environments.
const compareCanonical = (a, b) => a < b ? -1 : a > b ? 1 : 0;
const output = path.join(root, "docs", "CAPABILITY_ROUTE_SCHEMA_COVERAGE.md");

// Configure a local inspection server. These placeholders cannot authenticate.
process.env.NEXT_PUBLIC_SUPABASE_URL ||= "https://project.supabase.co";
process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY ||= "stub-anon-for-coverage";
process.env.SUPABASE_SERVICE_ROLE_KEY ||= "stub-service-for-coverage";

const app = from("server.js");
const { ROUTE_REGISTRY } = from("lib/sonara-route-registry.cjs");
const { accountRoutes, surfaceFor } = from("lib/sonara-route-surface.cjs");
const { RESOURCES } = from("lib/sonara-module-crud.cjs");
const { RESOURCE_MAP } = from("routes/sonara-last9-routes.cjs");
const { readOpenSourceTools } = from("lib/sonara-open-source-registry.cjs");
const { REQUESTED_REPOSITORIES } = from("lib/sonara-requested-repository-registry.cjs");
const { FORMULA_DEFINITIONS } = from("lib/sonara-formula-library.cjs");
const { FORMULAS } = from("lib/sonara-industry-algorithm-expansion.cjs");
const { SUBSYSTEMS } = from("lib/sonara-subsystem-registry.cjs");
const { INFRASTRUCTURE_SERVICES, PIPELINE_LAYERS } = from("lib/sonara-infrastructure-manifest.cjs");

const migrations = files("supabase/migrations").filter((name) => name.endsWith(".sql"));
const tableMigrations = new Map();
for (const filename of migrations) {
  const sql = fs.readFileSync(path.join(root, "supabase/migrations", filename), "utf8");
  const pattern = /\bCREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?(?:"?public"?\.)?"?([a-z][a-z0-9_]*)"?/gi;
  for (const match of sql.matchAll(pattern)) {
    const table = match[1].toLowerCase();
    if (!tableMigrations.has(table)) tableMigrations.set(table, []);
    tableMigrations.get(table).push(filename);
  }
}

const routeAccount = accountRoutes(app, ROUTE_REGISTRY.map(({ route }) => route));
if (routeAccount.unaccounted.length || routeAccount.ambiguous.length || routeAccount.served.length < 400) {
  throw new Error(`Route accounting failed: ${JSON.stringify({ unaccounted: routeAccount.unaccounted, ambiguous: routeAccount.ambiguous, count: routeAccount.served.length })}`);
}

const routeMethods = new Map();
for (const layer of app._router.stack) {
  if (!layer.route) continue;
  for (const route of Array.isArray(layer.route.path) ? layer.route.path : [layer.route.path]) {
    const methods = routeMethods.get(route) || new Set();
    for (const method of Object.keys(layer.route.methods)) methods.add(method.toUpperCase());
    routeMethods.set(route, methods);
  }
}
const registered = new Map(ROUTE_REGISTRY.map((item) => [item.route, item]));
const sortedRoutes = [...routeMethods].sort(([a], [b]) => compareCanonical(a, b));
const tableEvidence = (table) => {
  const names = tableMigrations.get(table) || [];
  return names.length ? `${table} (${names[0]})` : `${table} (migration unresolved)`;
};
const domain = (route) => {
  if (route.startsWith("/business-builder") || route.startsWith("/api/business")) return "Business Builder";
  if (route.startsWith("/creator-studio") || route.startsWith("/api/creator")) return "Creator Studio";
  if (route.startsWith("/growth-studio") || route.startsWith("/api/growth")) return "Growth Studio";
  if (route.startsWith("/admin") || route.startsWith("/owner")) return "Admin / owner";
  if (route.startsWith("/research-lab") || route.startsWith("/technology")) return "Research / technology";
  if (route.startsWith("/api")) return "Shared API";
  return "Shared / public";
};

const lines = [
  "# Capability, route and schema coverage",
  "",
  "Generated by `node scripts/generate-capability-coverage.mjs` from the current checkout. Run with `--check` to reject drift. This is a **code inventory**, not a claim that the deployed site works or that every operation has a complete UI, policy, test, and migration.",
  "",
  `Inventory: ${sortedRoutes.length} unique Express path shapes (${routeAccount.served.length} GET paths), ${tableMigrations.size} unique table names with CREATE TABLE evidence across ${migrations.length} migration files, ${readOpenSourceTools().length} curated external repositories, ${REQUESTED_REPOSITORIES.length} requested repositories, ${FORMULA_DEFINITIONS.length} formula definitions, ${FORMULAS.length} industry formula records.`,
  "",
  "The table count is the union of names found in tracked migration source, including historical migrations. It is not a production catalog count and does not prove that a table exists, is non-empty, is reachable, or is currently used. Use the production schema verifier and live database evidence for those claims.",
  "",
  "## Route and action inventory",
  "",
  "`GET` produces a page/file/response; write methods accept input and produce a response. Method presence alone does not establish a working form, tenant authorization, persistence, or provider connection. `Unresolved` means the route has no verified table link in the canonical resource maps; do not infer a table from its spelling.",
  "",
  "| Destination | Workspace | Methods / input → output | Route accounting | Verified table and first creating migration |",
  "| --- | --- | --- | --- | --- |"
];
for (const [route, methods] of sortedRoutes) {
  const spec = RESOURCE_MAP[route];
  // Shared CRUD uses a parameterised API; link it only when both product and resource match.
  const crud = Object.entries(RESOURCES).find(([key]) => {
    const [product, resource] = key.split(":");
    return route === `/api/${product.replace("_", "-")}/${resource}`;
  })?.[1];
  const table = spec?.table || crud?.table;
  const accounting = registered.has(route) ? "Page registry" : methods.has("GET") ? (surfaceFor(route)?.key || "Unresolved surface") : "Action route (no GET registry)";
  lines.push(`| ${cell(route)} | ${domain(route)} | ${[...methods].sort().join(", ")} | ${accounting} | ${table ? cell(tableEvidence(table)) : "Unresolved"} |`);
}

lines.push("", "## Canonical CRUD resource contracts", "", "These are explicit resource → table links, including routes that registration may expose through a parameterised handler. `migration unresolved` requires review before any schema change.", "", "| Resource or API path | Table / migration | Input fields |", "| --- | --- | --- |");
for (const [key, spec] of Object.entries(RESOURCES)) lines.push(`| ${cell(key)} | ${cell(tableEvidence(spec.table))} | ${cell(spec.editable.join(", "))} |`);
for (const [route, spec] of Object.entries(RESOURCE_MAP)) lines.push(`| ${cell(route)} | ${cell(tableEvidence(spec.table))} | ${cell((spec.required || []).join(", "))} |`);

lines.push("", "## Database schema creation index", "", "CREATE TABLE evidence only; later ALTER, policies, grants and remote applied state must be checked separately. No migrations are applied by this report.", "", "| Table | Creating migration(s) |", "| --- | --- |");
for (const [table, names] of [...tableMigrations].sort(([a], [b]) => compareCanonical(a, b))) lines.push(`| ${table} | ${names.map(cell).join(", ")} |`);

lines.push("", "## External repository placement", "", "A placement is a research destination, **not** permission to execute code. Status is taken from the curated register; verify upstream licence and current security before promotion.", "", "| Repository | Workspace destination | Intake status | Source |", "| --- | --- | --- | --- |");
const { surfacesFor } = from("lib/sonara-repository-product-routing.cjs");
for (const record of readOpenSourceTools().sort((a, b) => compareCanonical(a.name, b.name))) {
  lines.push(`| ${cell(record.name)} | ${cell(surfacesFor(record).map((s) => s.route).join(", "))} | ${cell(record.integrationStatus)} | data/open-source-tools.ts |`);
}
for (const record of REQUESTED_REPOSITORIES) {
  lines.push(`| ${cell(record.label)} | /research-lab/requested-repositories | ${cell(record.integrationStatus)} | lib/sonara-requested-repository-registry.cjs |`);
}
lines.push("", "### Other research intake files", "", "The following source registries are maintained separately. Inspect each record's status and license before assigning a runtime destination.", "");
for (const filename of files("lib").filter((name) => /screenshot-tool-radar|repository-intake|market.*registry|frontend-visual-intelligence/.test(name))) lines.push(`- \`lib/${filename}\``);

lines.push("", "## Formulas, agents, skills and infrastructure", "", "Formula definitions have input/output contracts, but a definition is not necessarily executable. Execution is governed by its evaluator. Agent and skill files are development or governed platform inputs, not customer actions by themselves.", "", "| Formula | Area | Inputs → output | Target tables |", "| --- | --- | --- | --- |");
for (const item of FORMULA_DEFINITIONS) lines.push(`| ${cell(item.formulaKey)} | ${cell(item.productArea)} | ${cell((item.requiredInputs || []).join(", "))} → ${cell(item.outputUnit)} | ${cell((item.targetTables || []).join(", "))} |`);
lines.push("", "### Industry formula registry", "", "These records describe candidate calculations; an entry here alone does not prove an executable handler.", "", "| Key | Domain | Expression / output definition |", "| --- | --- | --- |");
for (const item of FORMULAS) lines.push(`| ${cell(item.key)} | ${cell(item.domain)} | ${cell(item.expression)} |`);
lines.push("", `Schema-only/read-only subsystem groups: ${SUBSYSTEMS.length}. See \`lib/sonara-subsystem-registry.cjs\` and \`/research-lab/subsystems\`; these are not writable customer workspaces.`, "", "| Source | Governed destination |", "| --- | --- |");
for (const dir of [".claude/skills", "docs/agents", "infra", ".github/workflows"]) {
  for (const name of files(dir)) lines.push(`| ${cell(dir + "/" + name)} | ${dir === ".claude/skills" ? "Development skill" : dir === "docs/agents" ? "Agent governance" : "Infrastructure / delivery"} |`);
}
for (const name of files("lib").filter((entry) => /agent|formula/.test(entry) && entry.endsWith(".cjs"))) lines.push(`| lib/${name} | Governed runtime or registry; inspect before activation |`);
lines.push("", "### Infrastructure service and pipeline inventory", "", "Configured or planned dependencies; a manifest entry does not prove a healthy production connection.", "", "| Component | Launch status / layer | Declared endpoints |", "| --- | --- | --- |");
for (const item of INFRASTRUCTURE_SERVICES) lines.push(`| ${cell(item.label)} | ${cell(item.launchStatus)} | ${cell((item.endpoints || []).join(", "))} |`);
for (const item of PIPELINE_LAYERS) lines.push(`| ${cell(item.label)} | Delivery layer | — |`);
lines.push("", "## Gaps to resolve", "", `- ${sortedRoutes.filter(([route]) => !RESOURCE_MAP[route] && !Object.keys(RESOURCES).some((key) => { const [p, r] = key.split(":"); return route === `/api/${p.replace("_", "-")}/${r}`; })).length} routes have no proven direct link to either canonical CRUD resource map. This includes legitimate public pages, computed outputs, handlers with other persistence mechanisms, and routes needing inspection.`, "- A table's presence in SQL or a research repository's placement does not prove an input form, output handling, authorization, or a successful migration replay.", "- Next implementation step: link each write handler to its exact schema, RLS and audit contract, then test its form, API, and live tenant boundary before marking it active.", "");

const content = `${lines.join("\n").trimEnd()}\n`;
if (process.argv.includes("--check")) {
  const current = fs.existsSync(output) ? fs.readFileSync(output, "utf8") : "";
  if (current !== content) {
    const currentLines = current.split("\n");
    const expectedLines = content.split("\n");
    // This is strictly diagnostic; drift still fails the release gate.
    // A first mismatch hides the actual set difference when route totals tie.
    const routeRows = (rows) => new Map(rows.flatMap((line) => {
      const match = /^\| (\/[^|]+) \| /.exec(line);
      return match ? [[match[1], line]] : [];
    }));
    const checkedRoutes = routeRows(currentLines);
    const observedRoutes = routeRows(expectedLines);
    const checkedOnly = [...checkedRoutes.keys()].filter((name) => !observedRoutes.has(name));
    const observedOnly = [...observedRoutes.keys()].filter((name) => !checkedRoutes.has(name));
    const changed = [...observedRoutes].filter(([name, value]) =>
      checkedRoutes.has(name) && checkedRoutes.get(name) !== value)
      .map(([name]) => name);
    console.error("Coverage set difference (source document vs current checkout):", {
      checkedCount: checkedRoutes.size, observedCount: observedRoutes.size,
      checkedOnly: checkedOnly.slice(0, 25), observedOnly: observedOnly.slice(0, 25),
      changed: changed.slice(0, 25)
    });
    let index = 0;
    while (index < currentLines.length && index < expectedLines.length && currentLines[index] === expectedLines[index]) index += 1;
    const start = Math.max(0, index - 2);
    const end = Math.min(Math.max(currentLines.length, expectedLines.length), index + 3);
    console.error(`Capability coverage first mismatch at line ${index + 1}:`);
    for (let line = start; line < end; line += 1) {
      console.error(`  ${line + 1} current : ${currentLines[line] ?? "<missing>"}`);
      console.error(`  ${line + 1} expected: ${expectedLines[line] ?? "<missing>"}`);
    }
    throw new Error("Capability coverage document is stale; regenerate it.");
  }
} else fs.writeFileSync(output, content);
console.log(`Capability coverage: ${sortedRoutes.length} paths, ${tableMigrations.size} created tables, ${migrations.length} migrations.`);
