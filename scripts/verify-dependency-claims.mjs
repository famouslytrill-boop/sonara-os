#!/usr/bin/env node

// Prose that states how many production dependencies this application has.
//
// On 20 September 2026 the count went from one to nine, and on 21 September
// **seven live files still said one** -- a browser file shipped to customers, a
// release report, a test, three runtime modules and a register record. Each was
// load-bearing reasoning: no multipart parser because there is one dependency,
// no YAML parser because there is one dependency, this module adds no
// dependency "before a second arrives". A second had arrived, eight of them, and
// the sentences explaining decisions by the old count read exactly as they did
// when they were true.
//
// Nothing caught it. `report-stale-claims.mjs` watches dated claims in `docs/`;
// this claim is undated and mostly lives in source comments. So this is the
// check for the specific fact, because the general version -- "is every reason
// in every comment still true" -- is not a thing a script can do.
//
// ## Why a count claim and not a word
//
// The claim appears as digits ("9 production dependencies"), as words ("one
// production dependency", "nine production dependencies") and as an adjective
// ("single production dependency", "sole production dependency"). All three
// forms are read, because the first version of this matched digits only and
// found none of the seven -- every one of them was written in words.
//
// ## Past-tense statements are not current-state claims
//
// "went from one production dependency to nine" is a true sentence about a
// change, not a false sentence about today, so a count reached through a
// past-tense marker is not read as a claim. The marker list is short and named
// on purpose: an escape hatch wide enough to launder a current-state claim is
// worse than no check. "This is an Express 4 application with one production
// dependency" has no marker and fails, which is the case that motivated this.
//
// Whole documents are exempted separately. A dated finding that said "one
// production dependency" in August was correct in August, and rewriting it
// would rewrite the measurement. Those are listed in HISTORICAL with what makes
// them history, and the list is two-sided: an entry whose text can no longer be
// found fails, so an exemption cannot outlive the sentence it excuses.

import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const require_ = createRequire(path.join(root, "package.json"));

const WORDS = Object.freeze({
  no: 0, zero: 0, one: 1, single: 1, sole: 1, two: 2, three: 3, four: 4, five: 5,
  six: 6, seven: 7, eight: 8, nine: 9, ten: 10, eleven: 11, twelve: 12
});

// "one production dependency", "nine production dependencies",
// "single production dependency", "9 production dependencies".
const CLAIM = /\b([a-z]+|\d{1,3})[- ]production[- ]dependenc(?:y|ies)\b/gi;

// Immediately before the number, allowing one article: the phrasings that make
// the sentence a statement about the past rather than about now.
const PAST_TENSE = /\b(?:from|was|were|until|against|had|then)\s+(?:a|an|the)?\s*$/i;

// Sentences that were true when written and are dated as such. The key is the
// file; the value lists the exact fragment and why it stays.
const HISTORICAL = Object.freeze({
  "SECURITY_NOTES.md": [
    {
      fragment: "in the one production dependency's own tree",
      reason:
        "sits under the heading `### 2 September 2026`, describing advisories reached through express on that date, "
        + "when express was the only production dependency. Correcting it would misreport what was found."
    }
  ],
  "docs/SPRINT_LOG.md": [
    {
      fragment: "production dependenc",
      whole: true,
      reason:
        "the hand-written changelog. Every entry is a dated record of what was true when it was written, and this "
        + "check must not edit history. docs/HANDOFF_PROMPT.md embeds the most recent entries and is generated from it."
    }
  ],
  "docs/HANDOFF_PROMPT.md": [
    {
      fragment: "production dependenc",
      whole: true,
      reason:
        "generated by scripts/generate-handoff-prompt.mjs, which embeds the newest docs/SPRINT_LOG.md entries verbatim. "
        + "Editing it here would be undone by the next generation and would fail verify:handoff."
    }
  ],
  "data/open-source-tools.ts": [
    {
      fragment: "production dependenc",
      whole: true,
      reason:
        "every occurrence sits inside a dated licence finding or a recommendedAction that names the date the count "
        + "changed. .claude/skills/reviewing-an-outside-repository requires notes to say what was opened and when, so "
        + "the register records measurements rather than a current-state figure. Reviewed 21 September 2026: the four "
        + "present-tense guidance lines were corrected then, and what remains is history."
    }
  ]
});

const manifest = JSON.parse(fs.readFileSync(path.join(root, "package.json"), "utf8"));
const actual = Object.keys(manifest.dependencies || {}).length;

if (!Number.isFinite(actual) || actual < 1) {
  console.error(`ERROR: package.json declares ${actual} production dependencies; this check cannot vouch for a figure it cannot read.`);
  process.exit(1);
}

const { withoutComments } = require_("./lib/sonara-comment-stripping.cjs");

const tracked = execFileSync("git", ["ls-files"], { cwd: root, encoding: "utf8" })
  .split("\n")
  .filter(Boolean)
  .filter((file) => /\.(js|cjs|mjs|ts|md)$/.test(file))
  .filter((file) => !file.startsWith("archive/"))
  // This file states the claim in its own header, in prose, to explain itself.
  // A check that fails on its own explanation is one somebody deletes.
  .filter((file) => file !== "scripts/verify-dependency-claims.mjs");

if (tracked.length < 200) {
  console.error(`ERROR: only ${tracked.length} tracked file(s) to read; this check has gone blind rather than found nothing.`);
  process.exit(1);
}

const problems = [];
const exemptionsUsed = new Set();
let claimsChecked = 0;
let filesWithAClaim = 0;

function exemptionFor(file, sentence) {
  for (const entry of HISTORICAL[file] || []) {
    if (entry.whole || sentence.includes(entry.fragment)) {
      exemptionsUsed.add(`${file}::${entry.fragment}`);
      return entry;
    }
  }
  return null;
}

for (const file of tracked) {
  const raw = fs.readFileSync(path.join(root, file), "utf8");
  if (!/production[- ]dependenc/i.test(raw)) continue;
  filesWithAClaim += 1;
  // Comments are the whole point here, so nothing is stripped from source. The
  // shared stripper is imported only so that this file cannot be the fifth
  // place a hand-rolled one gets written; see
  // tests/a-line-comment-cannot-open-a-block-comment.test.js.
  void withoutComments;

  for (const match of raw.matchAll(CLAIM)) {
    const token = String(match[1]).toLowerCase();
    const claimed = Object.prototype.hasOwnProperty.call(WORDS, token)
      ? WORDS[token]
      : (/^\d+$/.test(token) ? Number(token) : null);
    // "its production dependency", "a production dependency" -- a determiner,
    // not a count. Nothing to check.
    if (claimed === null) continue;
    claimsChecked += 1;
    if (claimed === actual) continue;

    const at = match.index;
    if (PAST_TENSE.test(raw.slice(Math.max(0, at - 24), at))) continue;

    const sentence = raw.slice(Math.max(0, at - 200), at + 200).replace(/\s+/g, " ").trim();
    const exemption = exemptionFor(file, sentence);
    if (exemption) continue;

    const line = raw.slice(0, at).split("\n").length;
    problems.push(
      `${file}:${line} says "${match[0].trim()}"; package.json declares ${actual}\n`
      + `      ...${sentence}...`
    );
  }
}

// A pattern that matches nothing passes, which is the failure this whole file
// exists to prevent one level up. The claim is made in live source today; if a
// rewording drops it out of the pattern, that is the check going blind rather
// than the repository improving.
if (claimsChecked === 0) {
  console.error("ERROR: no production-dependency count claim was found anywhere in the repository.");
  console.error("Either every one was reworded out of this pattern, or the pattern stopped matching. Both need a human.");
  process.exit(1);
}

const staleExemptions = [];
for (const [file, entries] of Object.entries(HISTORICAL)) {
  for (const entry of entries) {
    if (exemptionsUsed.has(`${file}::${entry.fragment}`)) continue;
    if (!fs.existsSync(path.join(root, file))) {
      staleExemptions.push(`${file} -- the file is gone. Reason on record: ${entry.reason}`);
      continue;
    }
    const raw = fs.readFileSync(path.join(root, file), "utf8");
    if (!raw.includes(entry.fragment)) {
      staleExemptions.push(`${file} -- "${entry.fragment}" no longer appears. Reason on record: ${entry.reason}`);
    }
  }
}

if (problems.length || staleExemptions.length) {
  console.error(`Dependency claim check failed on ${problems.length + staleExemptions.length} point(s).\n`);
  if (problems.length) {
    console.error("These say a number of production dependencies that package.json does not declare. A comment");
    console.error("explaining a decision by a count that has changed reads exactly like one that is still true,");
    console.error("which is why this is a gate and not a note:");
    for (const problem of problems) console.error(`  - ${problem}`);
  }
  if (staleExemptions.length) {
    if (problems.length) console.error("");
    console.error("These HISTORICAL entries no longer excuse anything. Remove them: an exemption that outlives its");
    console.error("sentence is what the next reader believes instead of checking.");
    for (const stale of staleExemptions) console.error(`  - ${stale}`);
  }
  process.exit(1);
}

console.log(
  `Dependency claims verified: ${claimsChecked} count claim(s) across ${filesWithAClaim} file(s) mentioning production `
  + `dependencies, each agreeing with the ${actual} package.json declares, and `
  + `${Object.values(HISTORICAL).flat().length} dated historical statement(s) accounted for.`
);
