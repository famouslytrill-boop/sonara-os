"use strict";

// Derive which tables carry organization_id, straight from the migrations.
//
// lib/sonara-tenant-guard.cjs needs to know which tables are tenant-scoped so
// it can refuse an unscoped query against one. That list must not be
// hand-maintained -- a table added next month would be missing from it, and
// the guard would wave the new table's queries through while looking like it
// was working.
//
// supabase/migrations/ is not bundled into the Vercel function (vercel.json
// includes only public/, routes/ and lib/), so the list is generated into
// lib/ and committed. `pnpm run verify:tenant-tables` regenerates and fails on
// any difference, which is what keeps the committed copy honest.

const fs = require("node:fs");
const path = require("node:path");

const root = process.cwd();
const migrationsDir = path.join(root, "supabase", "migrations");
const outputPath = path.join(root, "lib", "sonara-tenant-scoped-tables.cjs");

function readMigrations() {
  if (!fs.existsSync(migrationsDir)) throw new Error(`missing ${migrationsDir}`);
  const files = fs.readdirSync(migrationsDir).filter((name) => name.endsWith(".sql")).sort();
  if (!files.length) throw new Error("no migrations found");
  return { files, sql: files.map((name) => fs.readFileSync(path.join(migrationsDir, name), "utf8")).join("\n") };
}

function classify(sql) {
  const tables = new Map();

  // A table is tenant-scoped if organization_id appears in its CREATE TABLE
  // body, or is added later by ALTER TABLE. Both spellings occur in this repo.
  const createPattern = /create\s+table\s+(?:if\s+not\s+exists\s+)?(?:public\.)?([a-z0-9_]+)\s*\(([\s\S]*?)\n\)\s*;/gi;
  for (const match of sql.matchAll(createPattern)) {
    const [, name, body] = match;
    if (!tables.has(name)) tables.set(name, false);
    if (/\borganization_id\b/i.test(body)) tables.set(name, true);
  }

  const alterPattern = /alter\s+table\s+(?:if\s+exists\s+)?(?:public\.)?([a-z0-9_]+)\s+add\s+column\s+(?:if\s+not\s+exists\s+)?organization_id/gi;
  for (const match of sql.matchAll(alterPattern)) tables.set(match[1], true);

  return {
    scoped: [...tables.entries()].filter(([, isScoped]) => isScoped).map(([name]) => name).sort(),
    unscoped: [...tables.entries()].filter(([, isScoped]) => !isScoped).map(([name]) => name).sort()
  };
}

const { files, sql } = readMigrations();
const { scoped, unscoped } = classify(sql);

if (scoped.length < 100) {
  // The parse silently returning almost nothing is the failure mode that would
  // disable the guard without anybody noticing. 206 were found when written.
  throw new Error(`only ${scoped.length} tenant-scoped tables parsed out of ${files.length} migrations; the parse is broken`);
}

const contents = `"use strict";

// GENERATED by scripts/generate-tenant-scoped-tables.cjs -- do not edit.
// Run \`pnpm run gen:tenant-tables\` after changing a migration.
//
// A table is listed as tenant-scoped when organization_id appears in its
// CREATE TABLE body or is added by a later ALTER TABLE. lib/sonara-tenant-guard.cjs
// refuses an unscoped query against anything in TENANT_SCOPED_TABLES.
//
// Parsed from ${files.length} migrations: ${scoped.length} tenant-scoped, ${unscoped.length} not.

const TENANT_SCOPED_TABLES = Object.freeze(new Set([
${scoped.map((name) => `  "${name}"`).join(",\n")}
]));

// Tables with no organization_id column. Listed so the guard can tell
// "deliberately global" from "not a table I know about" -- an unrecognised
// table name is suspicious, a known-global one is not.
const GLOBAL_TABLES = Object.freeze(new Set([
${unscoped.map((name) => `  "${name}"`).join(",\n")}
]));

module.exports = { TENANT_SCOPED_TABLES, GLOBAL_TABLES };
`;

const previous = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, "utf8") : "";
fs.writeFileSync(outputPath, contents);

if (process.argv.includes("--check")) {
  if (previous !== contents) {
    console.error("[fail] lib/sonara-tenant-scoped-tables.cjs is stale. Run `pnpm run gen:tenant-tables` and commit the result.");
    fs.writeFileSync(outputPath, previous || contents);
    process.exit(1);
  }
  console.log(`Tenant-scoped table list verified: ${scoped.length} scoped, ${unscoped.length} global, from ${files.length} migrations.`);
} else {
  console.log(`Wrote lib/sonara-tenant-scoped-tables.cjs: ${scoped.length} tenant-scoped, ${unscoped.length} global, from ${files.length} migrations.`);
}
