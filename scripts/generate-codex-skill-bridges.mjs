import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourceDir = path.join(repoRoot, ".claude/skills");
const managedDir = path.join(repoRoot, ".agents/skills");
const shared = [
  {
    "name": "sonara-external-tool-intake",
    "source": ".ai/shared/EXTERNAL_TOOL_RESEARCH_SKILL.md",
    "description": "Review external repositories, screenshots, skills, tools, licenses, risks and provenance before proposing SONARA adoption. Use on any outside code or tool integration request."
  },
  {
    "name": "sonara-source-grounding",
    "source": ".ai/shared/SOURCE_GROUNDED_RESEARCH_SKILL.md",
    "description": "Ground SONARA technical, market or security research in direct evidence, verify citations, identify contradictions and preserve uncertainty before making implementation decisions."
  }
];
const formulas = {
  "name": "sonara-formula-evidence",
  "description": "Locate, interpret and verify SONARA formula definitions, calculator handlers, quantitative modules and strategic algorithms. Use for financial, restaurant, logistics, science, planning and other calculations; confirm units, executable status, licensing and tests before applying results."
};
const extract = (path,source)=>{
 const f=/^---\r?\n([\s\S]*?)\r?\n---/.exec(source);
 if(!f)throw new Error(`No frontmatter: ${path}`);
 const name=/^name:\s*([a-z0-9]+(?:-[a-z0-9]+)*)\s*$/m.exec(f[1])?.[1];
 const description=/^description:\s*(.+)$/m.exec(f[1])?.[1]?.trim();
 if(!name||!description||description.length>900)throw new Error(`Invalid name/description: ${path}`);
 return {name,description};
}
const front = (name,description)=>`---\nname: ${name}\ndescription: ${description}\n---\n\n`
const bridge = (m)=>front(m.name,m.description)+`# ${m.name}: Codex bridge\n\nThis is a **generated discovery bridge**, not a duplicate skill. The canonical SONARA-owned instructions live in \`${m.path}\`.\n\n1. Read \`AGENTS.md\` for repository authority and policy.\n2. Read the complete \`${m.path}\` before using this skill; treat any Claude-specific wording as applying to Codex too, subject to the actual available tools.\n3. Read only relevant task-specific formula implementations, schemas and tests, guided by \`.ai/shared/ASSISTANT_KNOWLEDGE_INDEX.md\`.\n4. Do not treat research entries, formula metadata, tests with mocked providers, or documented proposals as proof of live functionality.\n5. Observe tenant boundaries, approval gates, licensing, cost budgets and exact-head CI. A skill never grants tool access.\n\n<!-- Generated by scripts/generate-codex-skill-bridges.mjs; do not hand edit. -->\n`
const sharedBridge = (m)=>front(m.name,m.description)+`# ${m.name}: Codex shared procedure\n\nRead \`AGENTS.md\` and the entire canonical procedure at \`${m.source}\`. Apply it only to authorized SONARA work. The pointer is for local repository access; it is not an installed ChatGPT app, a model weight update, or an authorization grant.\n\n<!-- Generated by scripts/generate-codex-skill-bridges.mjs; do not hand edit. -->\n`
const formulaBridge = "---\nname: sonara-formula-evidence\ndescription: Locate, interpret and verify SONARA formula definitions, calculator handlers, quantitative modules and strategic algorithms. Use for financial, restaurant, logistics, science, planning and other calculations; confirm units, executable status, licensing and tests before applying results.\n---\n\n# SONARA formula-evidence skill\n\nUse for any calculation, algorithm, projection, score or source-grounded mathematical assertion. This skill is a discovery and validation procedure, not an execution grant.\n\n1. Read `AGENTS.md`, `.ai/shared/PROJECT_MEMORY.md` and `.ai/shared/ASSISTANT_KNOWLEDGE_INDEX.md` for repository pointers.\n2. Choose an appropriate domain and **source-qualified formula**. Examine `lib/sonara-formula-library.cjs`, `lib/sonara-industry-algorithm-expansion.cjs`, `lib/sonara-formula-engine.cjs`, `lib/sonara-financial-intelligence-formulas.cjs` and other indexed quantitative modules as relevant.\n3. Distinguish `research_only`, `registered`, `allowlisted_executable`, `tested` and `production_verified`. A document/SQL registration does not make a calculation callable or correct.\n4. Validate the input domain, units, currency, period, dimension, timezone, zero denominators, null values, precision/rounding, authoritative source, provenance, and relevant industry/legal restrictions. Never infer missing values as zero.\n5. For executable formulas, use the existing allowlisted deterministic implementation. Do **not** `eval` expressions, run arbitrary spreadsheet formulas/macros, route through an AI provider unnecessarily or invent a mathematical result.\n6. Compare expected outputs against independent examples; test malformed, boundary, cross-tenant and missing-input cases. Falsify any added check on a deliberately bad fixture; keep the original unchanged.\n7. Report assumptions, input lineage, formula version, computed or unavailable state, and whether it was tested locally or exercised in live production. No formula can authorize payments, trades, legal/medical determinations, destructive changes or deployment.\n\n<!-- Generated by scripts/generate-codex-skill-bridges.mjs; do not hand edit. -->\n";

function buildExpected() {
  const directories = fs.readdirSync(sourceDir,{withFileTypes:true}).filter(e=>e.isDirectory()).map(e=>e.name).sort();
  if(directories.length < 12)throw new Error("Claude skill discovery returned unexpectedly few directories");
  const metadata = directories.map(dir=>{
    const sourcePath = `.claude/skills/${dir}/SKILL.md`;
    const source = fs.readFileSync(path.join(repoRoot,sourcePath),"utf8");
    const fields = extract(sourcePath,source);
    if(fields.name!==dir)throw new Error("Skill name/dirname mismatch: "+sourcePath);
    return {path:sourcePath,...fields};
  });
  const used=new Set();
  for(const item of [...metadata,...shared,formulas]){
    if(used.has(item.name))throw new Error("Conflicting skill name: "+item.name);
    used.add(item.name);
  }
  for(const item of shared)if(!fs.existsSync(path.join(repoRoot,item.source)))throw new Error("Missing shared procedure: "+item.source);
  return new Map([...metadata.map(item=>[`.agents/skills/${item.name}/SKILL.md`,bridge(item)]),...shared.map(item=>[`.agents/skills/${item.name}/SKILL.md`,sharedBridge(item)]),[`.agents/skills/${formulas.name}/SKILL.md`,formulaBridge]]);
}

function main() {
 const list=buildExpected();
 const checking=process.argv.includes("--check");
 if(!checking&&!process.argv.includes("--write"))throw new Error("Specify --check or --write");
 const failures=[];
 for(const [relativePath,contents] of list){
   const dest=path.join(repoRoot,relativePath);
   if(checking){
     if(!fs.existsSync(dest)||fs.readFileSync(dest,"utf8")!==contents)failures.push(relativePath);
   }else{
     fs.mkdirSync(path.dirname(dest),{recursive:true});
     fs.writeFileSync(dest,contents,"utf8");
   }
 }
 // Detect orphaned generated bridges without deleting files that might be user-owned.
 if(fs.existsSync(managedDir))for(const entry of fs.readdirSync(managedDir,{withFileTypes:true})){
   if(!entry.isDirectory())continue;
   const rel=`.agents/skills/${entry.name}/SKILL.md`;
   if(list.has(rel))continue;
   const f=path.join(managedDir,entry.name,"SKILL.md");
   if(fs.existsSync(f)&&fs.readFileSync(f,"utf8").includes("Generated by scripts/generate-codex-skill-bridges.mjs"))failures.push("orphan:"+rel);
 }
 if(failures.length){console.error("Codex skills out of sync: "+failures.join(", "));process.exitCode=1;return;}
 console.log(`Codex skill bridges ${checking?"verified":"generated"}: ${list.size} (canonical + shared + formula).`);
}
main();
