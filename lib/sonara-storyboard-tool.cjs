"use strict";

// A storyboard that adds up.
//
// ## Why this is a calculator and not a prompt
//
// The version of this circulating as a prompt -- "generate a complete cinematic
// storyboard, 8 frames, A4, premium infographic design" -- produces a handsome
// document whose durations do not sum to the runtime. That is not a small
// failing. A creator books a shoot, a voice artist and an edit against those
// numbers, and discovers on the timeline that the shot list was thirty seconds
// long for a fifteen-second slot.
//
// So the arithmetic is the product here. Every shot gets whole seconds, the
// seconds sum to exactly the runtime asked for, and the remainder from the
// division is placed rather than dropped.
//
// The *shape* -- hook, subject, tension, demonstration, message, payoff, climax,
// ending -- is standard film grammar, in every screenwriting text for fifty
// years, and belongs to nobody. What is ours is the weighting: the hook and the
// ending get more time than an even split gives them, because those are the two
// shots that decide whether the middle is watched at all.
//
// Nothing here is generated by a model and nothing is sent anywhere. It runs on
// the inputs, at no cost per use.

const BEATS = [
  { name: "Hook", weight: 1.5, purpose: "Open on the strongest image you have. Nothing establishes, nothing warms up.", camera: "Close, static or a slow push in" },
  { name: "Subject", weight: 1.0, purpose: "Show who or what this is about, once, clearly.", camera: "Medium, eye level" },
  { name: "Tension", weight: 1.0, purpose: "Name the problem the viewer already has.", camera: "Handheld or slight movement" },
  { name: "Demonstration", weight: 1.25, purpose: "Show the thing working. Not described -- shown.", camera: "Close on hands, product or detail" },
  { name: "Message", weight: 1.0, purpose: "The one sentence you would keep if you could keep only one.", camera: "Wide, steady" },
  { name: "Payoff", weight: 1.0, purpose: "The result, the relief, the outcome.", camera: "Medium, natural light" },
  { name: "Climax", weight: 1.25, purpose: "The most striking frame of the piece.", camera: "Wide or dramatic angle" },
  { name: "Ending", weight: 1.5, purpose: "Say what to do next. One action, not three.", camera: "Static, room for text" }
];

const TRANSITIONS = ["Cut", "Cut", "Match cut", "Cut", "Cut on action", "Cut", "Cut", "Hold, then fade"];

function numberFrom(value) {
  const cleaned = String(value == null ? "" : value).replace(/[,\s]/g, "");
  if (!cleaned) return null;
  const parsed = Number(cleaned);
  return Number.isFinite(parsed) ? parsed : null;
}

// Whole seconds per shot that sum to exactly `total`.
//
// Largest-remainder rather than rounding each independently: rounding eight
// shots separately loses or gains up to four seconds against the runtime, which
// is the defect this whole file exists to avoid.
function allocateSeconds(total, weights) {
  const sum = weights.reduce((carry, weight) => carry + weight, 0);
  const exact = weights.map((weight) => (weight / sum) * total);
  const floors = exact.map((value) => Math.floor(value));
  let remainder = total - floors.reduce((carry, value) => carry + value, 0);
  const order = exact
    .map((value, index) => ({ index, fraction: value - Math.floor(value) }))
    .sort((a, b) => b.fraction - a.fraction);
  const seconds = [...floors];
  let cursor = 0;
  while (remainder > 0 && order.length) {
    seconds[order[cursor % order.length].index] += 1;
    remainder -= 1;
    cursor += 1;
  }
  return seconds;
}

function buildStoryboard(body) {
  const duration = numberFrom(body.durationSeconds);
  const requested = numberFrom(body.sceneCount);
  const idea = String(body.videoIdea || "").trim();

  if (duration === null || duration <= 0) {
    return {
      couldNotCalculate: "We could not read the runtime in seconds, and every figure below would be derived from it.",
      whatToDo: "Enter the length in whole seconds -- 30 rather than half a minute.",
      nothingWasGuessed: "No shot list has been produced, because one built on a guessed runtime is worse than none."
    };
  }
  if (!idea) {
    return {
      couldNotCalculate: "No video idea was entered, so there is nothing to build a shot list around.",
      whatToDo: "Say in one line what the video is for, then run it again.",
      nothingWasGuessed: "No subject has been invented on your behalf."
    };
  }

  // Between three and eight. Fewer than three has no shape; more than eight in a
  // short piece gives shots too brief to read.
  const count = Math.max(3, Math.min(requested === null ? 8 : Math.round(requested), BEATS.length));
  const beats = count === BEATS.length
    ? BEATS
    : [BEATS[0], ...BEATS.slice(1, BEATS.length - 1).slice(0, count - 2), BEATS[BEATS.length - 1]];

  const seconds = allocateSeconds(Math.round(duration), beats.map((beat) => beat.weight));
  const platform = String(body.platform || "").trim();
  const style = String(body.style || "").trim();

  let elapsed = 0;
  const shots = beats.map((beat, index) => {
    const start = elapsed;
    elapsed += seconds[index];
    return `${index + 1}. ${beat.name} — ${seconds[index]}s (${start}s–${elapsed}s) | ${beat.camera} | ${beat.purpose} | Next: ${TRANSITIONS[Math.min(index, TRANSITIONS.length - 1)]}`;
  });

  const shortest = Math.min(...seconds);
  return {
    video: idea,
    runtime: `${Math.round(duration)} seconds across ${beats.length} shots.`,
    shotList: shots.join("  ||  "),
    // The claim this tool is allowed to make, because it is checked below.
    durationsAddUp: `The shots total ${seconds.reduce((carry, value) => carry + value, 0)} seconds, which is the runtime you asked for. Nothing has been rounded away.`,
    shortestShot: shortest < 2
      ? `Your shortest shot is ${shortest}s, which is below the point a viewer can read anything on screen. Either lengthen the video or cut a shot.`
      : `Shortest shot is ${shortest}s, long enough to register.`,
    onScreenText: platform
      ? `For ${platform}: keep captions inside the middle two thirds of the frame, and assume it is watched with the sound off until the hook has earned it.`
      : "No platform entered. Keep captions inside the middle two thirds of the frame, and assume the sound is off until the hook has earned it.",
    style: style ? `Look: ${style}. Decide it before the first shot, not in the edit.` : "No look entered. Choose one before the shoot; deciding in the edit is how a piece ends up with three.",
    rights: "Clear the music, any footage you did not shoot, and anybody recognisable in the frame before this is published."
  };
}


